def get_random_hook() -> tuple[str, str, str]:
    """Pick a hook line, subline, palette — never repeat consecutively."""
    global _last_hook_idx
    available = list(range(len(HOOK_LINES)))
    if _last_hook_idx >= 0 and len(available) > 1:
        available.remove(_last_hook_idx)
    idx = random.choice(available)
    _last_hook_idx = idx
    return HOOK_LINES[idx]


